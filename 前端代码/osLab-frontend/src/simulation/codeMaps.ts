export function getCodeMap(algorithmKey: string): AlgorithmCodeMap | undefined {
  return CODE_MAPS[algorithmKey];
}

/** 无事件或无映射时返回空数组，绝不猜测代码行。 */
export function resolveActiveCodeLines(
  algorithmKey: string,
  event?: DemoEvent
): number[] {
  const map = getCodeMap(algorithmKey);
  if (!map || !event || !event.kind) return [];
  const lines = map.eventMap[event.kind];
  return Array.isArray(lines) ? lines.slice() : [];
}

interface CpuStepState {
  process?: string | null;
  start?: number;
  end?: number;
  level?: number;
}

interface PageStepState {
  page?: number | null;
  fault?: boolean;
  evicted?: number | null;
}

interface AllocationBlockView {
  start: number;
  size: number;
  process: string | null;
}

interface AllocationStepState {
  success?: boolean;
  blocks?: AllocationBlockView[];
}

interface DiskStepState {
  from?: number | null;
  head?: number;
  target?: number | null;
  request?: number | null;
  movement?: number;
  actionType?: string;
}

function cpuEvent(step: DemoStep): DemoEvent {
  const state = step.state as CpuStepState;
  const start = Number(state.start ?? 0);
  const end = Number(state.end ?? step.time ?? start);
  const duration = Math.max(0, end - start);
  if (state.process === null || state.process === undefined) {
    return { kind: "cpu.idle", from: "ready", to: "idle", duration };
  }
  return {
    kind: "cpu.run",
    objectId: String(state.process),
    from: state.level === undefined ? "ready" : `Q${state.level}`,
    to: String(state.process),
    duration,
  };
}

function pageEvent(step: DemoStep): DemoEvent {
  const state = step.state as PageStepState;
  if (state.page === null || state.page === undefined) {
    return { kind: "page.load" };
  }
  const evicted = state.evicted ?? null;
  const kind = !state.fault
    ? "page.hit"
    : evicted !== null
    ? "page.replace"
    : "page.load";
  return {
    kind,
    objectId: String(state.page),
    from: evicted === null ? undefined : String(evicted),
    to: String(state.page),
  };
}

function allocationEvent(
  input: AllocationInput,
  step: DemoStep,
  index: number
): DemoEvent | undefined {
  const operation = input.operations[index];
  if (!operation) return undefined;
  const state = step.state as AllocationStepState;
  const success = Boolean(state.success);
  const allocated = (state.blocks || []).find(
    (block) => block.process === operation.process
  );
  const kind =
    operation.type === "FREE"
      ? success
        ? "allocation.free"
        : "allocation.free_fail"
      : success
      ? "allocation.alloc"
      : "allocation.alloc_fail";
  if (operation.type === "FREE") {
    return {
      kind,
      objectId: operation.process,
      from: operation.process,
      to: success ? "free" : "unreleased",
    };
  }
  return {
    kind,
    objectId: operation.process,
    from: "free",
    to:
      success && allocated
        ? `[${allocated.start},${allocated.start + allocated.size})`
        : "unallocated",
  };
}

function diskEvent(step: DemoStep): DemoEvent {
  const state = step.state as DiskStepState;
  const target = state.target ?? state.request ?? state.head ?? 0;
  const from = state.from ?? state.head ?? target;
  const kind =
    state.actionType === "JUMP"
      ? "disk.jump"
      : state.actionType === "BOUNDARY"
      ? "disk.boundary"
      : "disk.seek";
  return {
    kind,
    objectId: String(target),
    from: String(from),
    to: String(target),
    duration: Math.abs(Number(target) - Number(from)),
  };
}

function deriveEvent(
  definition: AlgorithmDefinition,
  input: DemoInput,
  step: DemoStep,
  index: number
): DemoEvent | undefined {
  if (definition.category === "cpu") return cpuEvent(step);
  if (definition.category === "page") return pageEvent(step);
  if (definition.category === "allocation") {
    return allocationEvent(input as AllocationInput, step, index);
  }
  if (definition.category === "disk") return diskEvent(step);
  return undefined;
}

/**
 * 为真值步骤补上事件与活动代码行。
 * 不修改原 result；已有 event/codeLines 的步骤保持原值。
 */
export function annotateResult(
  definition: AlgorithmDefinition,
  input: DemoInput,
  result: DemoResult
): DemoResult {
  const steps = result.steps.map((step, index) => {
    const event = step.event ?? deriveEvent(definition, input, step, index);
    const active =
      step.activeCodeLines ??
      step.codeLines ??
      resolveActiveCodeLines(definition.key, event);
    return {
      ...step,
      event,
      codeLines: step.codeLines ?? (active.length ? active.slice() : undefined),
      activeCodeLines: active.slice(),
    };
  });
  return { ...result, steps };
}

